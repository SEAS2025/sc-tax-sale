"use strict";

/**
 * Structural, column-addressed reader for published delinquent-tax tables.
 *
 * Why this exists: the Haywood County advertised list is an HTML table whose
 * parcel column holds the North Carolina grid PIN with the hyphens stripped —
 * a bare 10-digit run. Matching that with a global /\d{10}/ regex would also
 * swallow phone numbers, asset ids, and totals from elsewhere on the page, so
 * the parcel is located by *column position* instead: find the header row,
 * find the index of the PARCEL column, and read only that column.
 *
 * Owner safety: these pages carry a LIABLE OWNER column. The owner column
 * index is identified solely so it can be dropped. No owner value is ever
 * returned, stored, or logged by this module — only parcel and amount.
 */

const { parseAmount } = require("./csv");

const PARCEL_HEADER_RE = /^(parcel|parcel\s*(?:no|number|id)|pin|apn|tax\s*parcel|map\s*(?:no|number)|property\s*id)\b/i;
const AMOUNT_HEADER_RE = /^(amount|amount\s*due|total|total\s*due|tax\s*due|balance|delinquent\s*amount)\b/i;
const OWNER_HEADER_RE = /(owner|taxpayer|name|liable)/i;
const YEARS_HEADER_RE = /^(tax\s*years?|years?|year)\b/i;
const ACRES_HEADER_RE = /^(acres|acreage|acerage)\b/i;
const SITUS_HEADER_RE = /^(situs|location|address|property\s*address)\b/i;
const PSEUDO_HEADER_RE = /^field\s*\d+$/i;

/* ------------------------------------------------------------ HTML → cells */

function decodeEntities(text) {
  return String(text || "")
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&quot;/gi, '"')
    .replace(/&#3[49];/g, "'")
    .replace(/&#(\d+);/g, (_m, d) => String.fromCharCode(Number(d)));
}

function cellText(html) {
  return decodeEntities(String(html || "").replace(/<[^>]+>/g, " "))
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Split an HTML document into tables of row arrays. Cells are read from both
 * th and td so a row that uses th for its first column still lines up.
 */
function parseTables(html) {
  const blob = String(html || "").replace(/<(script|style)[^>]*>[\s\S]*?<\/\1>/gi, " ");
  const tables = [];
  const tableRe = /<table\b[^>]*>([\s\S]*?)<\/table>/gi;
  let tableMatch;
  while ((tableMatch = tableRe.exec(blob))) {
    const rows = [];
    const rowRe = /<tr\b[^>]*>([\s\S]*?)<\/tr>/gi;
    let rowMatch;
    while ((rowMatch = rowRe.exec(tableMatch[1]))) {
      const cells = [];
      const cellRe = /<(th|td)\b[^>]*>([\s\S]*?)<\/\1>/gi;
      let cellMatch;
      while ((cellMatch = cellRe.exec(rowMatch[1]))) cells.push(cellText(cellMatch[2]));
      if (cells.length) rows.push(cells);
    }
    if (rows.length) tables.push(rows);
  }
  return tables;
}

/* ------------------------------------------------------------ header lookup */

function columnMap(headerCells) {
  const map = { parcel: -1, amount: -1, owner: -1, taxYears: -1, acres: -1, situs: -1 };
  headerCells.forEach((raw, index) => {
    const cell = String(raw || "").trim();
    if (!cell) return;
    if (map.parcel < 0 && PARCEL_HEADER_RE.test(cell)) map.parcel = index;
    else if (map.amount < 0 && AMOUNT_HEADER_RE.test(cell)) map.amount = index;
    else if (map.taxYears < 0 && YEARS_HEADER_RE.test(cell)) map.taxYears = index;
    else if (map.acres < 0 && ACRES_HEADER_RE.test(cell)) map.acres = index;
    else if (map.situs < 0 && SITUS_HEADER_RE.test(cell)) map.situs = index;
    else if (map.owner < 0 && OWNER_HEADER_RE.test(cell)) map.owner = index;
  });
  return map;
}

/**
 * Locate the real header row. A "Field 1 / Field 2 / Field 3" row generated by
 * the publishing CMS sits above it and is skipped.
 */
function findHeaderRow(rows, limit) {
  const max = Math.min(rows.length, limit || 12);
  for (let i = 0; i < max; i += 1) {
    const cells = rows[i];
    if (cells.every((cell) => PSEUDO_HEADER_RE.test(cell) || cell === "")) continue;
    const map = columnMap(cells);
    if (map.parcel >= 0) return { index: i, map, cells };
  }
  return null;
}

/* -------------------------------------------------------- parcel validation */

const NC_PIN_DIGITS = 10;

/**
 * Canonical parcel form.
 *
 * North Carolina: the Haywood advertised list publishes the grid PIN with its
 * hyphens stripped (for example 8614733009), so the canonical form kept here is
 * that same digits-only 10-character string. Both sides of every intersection
 * are normalized this way, and a hyphenated 8614-73-3009 from any other source
 * collapses to the identical key.
 *
 * Arizona: assessor parcel numbers are canonicalized to digits plus an optional
 * split suffix and book/map/parcel letter, hyphens removed.
 */
function normalizeParcel(raw, stateCode) {
  const text = String(raw == null ? "" : raw).toUpperCase().trim();
  if (!text) return null;
  const state = String(stateCode || "").toUpperCase();
  if (state === "NC") {
    const digits = text.replace(/\D/g, "");
    if (digits.length !== NC_PIN_DIGITS) return null;
    if (/^(19|20)\d{8}$/.test(digits) && !/-/.test(text)) {
      // A bare 10-digit run beginning 19xx/20xx is far more likely a date or a
      // phone-style value than an NC grid PIN, so it is refused.
      return null;
    }
    return digits;
  }
  if (state === "AZ") {
    const match = text.match(/^(\d{3})-?(\d{2})-?(\d{3})([A-Z])?(?:\.(\d{1,3}))?$/);
    if (!match) return null;
    return match[1] + match[2] + match[3] + (match[4] || "") + (match[5] ? "." + match[5] : "");
  }
  const generic = text.replace(/\s+/g, "");
  return generic.length >= 6 ? generic : null;
}

function looksLikeParcelColumn(rows, header, stateCode, sample) {
  const limit = Math.min(rows.length, (sample || 40) + header.index + 1);
  let seen = 0;
  let good = 0;
  for (let i = header.index + 1; i < limit; i += 1) {
    const cell = rows[i][header.map.parcel];
    if (cell == null || cell === "") continue;
    seen += 1;
    if (normalizeParcel(cell, stateCode)) good += 1;
  }
  return seen >= 3 && good / seen >= 0.8;
}

/* ------------------------------------------------------------------ reading */

/**
 * Read parcel and amount out of every published table in a document.
 *
 * Returns identifiers and amounts only. The owner column is located and then
 * deliberately skipped; its contents never leave this function.
 */
function readParcelTables(html, stateCode) {
  const tables = parseTables(html);
  const out = {
    stateCode: String(stateCode || "").toUpperCase(),
    tables: [],
    rows: [],
    ids: [],
    amounts: {},
    rowCount: 0,
    droppedOwnerColumn: false,
    rejected: 0,
  };
  const seen = new Map();
  for (const rows of tables) {
    const header = findHeaderRow(rows);
    if (!header) continue;
    if (!looksLikeParcelColumn(rows, header, stateCode)) continue;
    const info = {
      headerRowIndex: header.index,
      headers: header.cells.slice(),
      parcelColumn: header.map.parcel,
      amountColumn: header.map.amount,
      ownerColumnDropped: header.map.owner >= 0 ? header.map.owner : null,
      dataRows: 0,
      kept: 0,
    };
    if (header.map.owner >= 0) out.droppedOwnerColumn = true;
    for (let i = header.index + 1; i < rows.length; i += 1) {
      const cells = rows[i];
      const rawParcel = cells[header.map.parcel];
      if (rawParcel == null || rawParcel === "") continue;
      info.dataRows += 1;
      const parcel = normalizeParcel(rawParcel, stateCode);
      if (!parcel) {
        out.rejected += 1;
        continue;
      }
      const amount = header.map.amount >= 0 ? parseAmount(cells[header.map.amount]) : null;
      const row = { parcel, amount: Number.isFinite(amount) ? amount : null };
      if (header.map.taxYears >= 0) {
        const years = String(cells[header.map.taxYears] || "").match(/(?:19|20)\d{2}/g);
        if (years) row.taxYears = [...new Set(years)].join(", ");
      }
      if (header.map.acres >= 0) {
        const acres = Number(String(cells[header.map.acres] || "").replace(/[^\d.]/g, ""));
        if (Number.isFinite(acres) && acres > 0) row.acres = acres;
      }
      if (header.map.situs >= 0) {
        const situs = String(cells[header.map.situs] || "").trim();
        if (situs) row.situs = situs;
      }
      info.kept += 1;
      out.rows.push(row);
      if (!seen.has(parcel)) {
        seen.set(parcel, row.amount);
      } else if (row.amount != null && seen.get(parcel) == null) {
        seen.set(parcel, row.amount);
      }
    }
    out.tables.push(info);
  }
  out.rowCount = out.rows.length;
  out.ids = [...seen.keys()];
  out.amounts = Object.fromEntries(seen);
  out.count = out.ids.length;
  return assertNoOwnerLeak(out);
}

/* ------------------------------------------- columnar PDF / plain-text lists */

const COLUMN_HEADER_RE = /(liable\s+owner|owner|taxpayer)\s{2,}(parcel|pin)\b/i;

/**
 * How far a parcel token may sit from its column heading. Measured against the
 * six real Haywood 2017 advertisement pages: all 4,115 published rows land
 * within 7 characters of a `Parcel` heading, so 12 is lossless and still tight
 * enough to reject numbers printed elsewhere on the page.
 */
const COLUMN_TOLERANCE = 12;

/**
 * Read a newspaper-style advertisement rendered by `pdftotext -layout`.
 *
 * The Haywood advertisement prints five side-by-side
 * "Liable Owner | Parcel | Amount" column groups per page. The character
 * position of every `Parcel` heading is taken from the header line, and a
 * value is accepted only when it sits under one of those headings *and* is
 * followed immediately by its dollar amount. Anchoring on the heading keeps
 * this column-addressed — a number printed anywhere else on the page is out of
 * range and ignored — while tolerating the small drift that occurs when a long
 * owner name pushes into the next column.
 *
 * The owner portion of each group is never read.
 */
function readColumnarText(text, stateCode) {
  const lines = String(text || "").split(/\r?\n/);
  const out = {
    stateCode: String(stateCode || "").toUpperCase(),
    groups: 0,
    parcelColumns: [],
    rows: [],
    ids: [],
    amounts: {},
    rowCount: 0,
    droppedOwnerColumn: false,
    rejected: 0,
  };
  const seen = new Map();
  let parcelColumns = null;
  for (const line of lines) {
    if (COLUMN_HEADER_RE.test(line)) {
      const columns = [...line.matchAll(/\b(?:parcel|pin)\b/gi)].map((m) => m.index);
      if (columns.length) {
        parcelColumns = columns;
        out.groups = Math.max(out.groups, columns.length);
        out.parcelColumns = columns.slice();
        out.droppedOwnerColumn = true;
      }
      continue;
    }
    if (!parcelColumns) continue;
    const re = /(\d[\d-]{8,13})\s*(?:\((?:subd|sub|div)\.?\))?\s+\$?([\d,]+\.\d{2})/g;
    let match;
    while ((match = re.exec(line))) {
      const underColumn = parcelColumns.some((column) => Math.abs(match.index - column) <= COLUMN_TOLERANCE);
      if (!underColumn) {
        out.rejected += 1;
        continue;
      }
      const parcel = normalizeParcel(match[1], stateCode);
      if (!parcel) {
        out.rejected += 1;
        continue;
      }
      const amount = parseAmount(match[2]);
      const row = { parcel, amount: Number.isFinite(amount) ? amount : null };
      out.rows.push(row);
      if (!seen.has(parcel)) seen.set(parcel, row.amount);
      else if (row.amount != null && seen.get(parcel) == null) seen.set(parcel, row.amount);
    }
  }
  out.rowCount = out.rows.length;
  out.ids = [...seen.keys()];
  out.amounts = Object.fromEntries(seen);
  out.count = out.ids.length;
  return assertNoOwnerLeak({ ...out, tables: [] });
}

const OWNER_SHAPE_RE = /[A-Z]{2,}\s*,\s*[A-Z]{2,}|\bLLC\b|\bINC\b|\bTRUST\b|\bHEIRS\b|\bETAL\b|\bEXR\b/;

/**
 * Last line of defence: nothing owner-shaped may appear in the returned
 * structure. Parcel keys are digits, amounts are numbers, and the optional
 * situs/tax-year fields are checked for owner-looking text.
 */
function assertNoOwnerLeak(result) {
  const blob = JSON.stringify({
    ids: result.ids,
    amounts: result.amounts,
    rows: result.rows,
    tables: result.tables.map((t) => ({ ...t, headers: undefined })),
  });
  if (OWNER_SHAPE_RE.test(blob.toUpperCase())) {
    throw new Error("out-of-state table reader refused to return owner-shaped text");
  }
  return result;
}

module.exports = {
  parseTables,
  columnMap,
  findHeaderRow,
  normalizeParcel,
  looksLikeParcelColumn,
  readParcelTables,
  readColumnarText,
  cellText,
  OWNER_HEADER_RE,
  COLUMN_HEADER_RE,
  COLUMN_TOLERANCE,
};
